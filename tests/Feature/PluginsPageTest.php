<?php

use App\Filament\Pages\Plugins;
use App\Models\User;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Http;
use Livewire\Livewire;

function writeInstalledPlugins(array $plugins): void
{
    File::put(config('wave.plugins_path').'/installed.json', json_encode($plugins));
}

function readInstalledPlugins(): string
{
    return File::get(config('wave.plugins_path').'/installed.json');
}

beforeEach(function () {
    $this->actingAs(User::factory()->admin()->create());

    $this->pluginsPath = $this->useTemporaryPluginsPath();
    $this->victim = dirname($this->pluginsPath).'/plugin-traversal';

    File::ensureDirectoryExists($this->pluginsPath.'/test-fixture');
    File::put($this->pluginsPath.'/test-fixture/TestFixturePlugin.php', <<<'PHP'
<?php

namespace Wave\Plugins\TestFixture;

use Wave\Plugins\Plugin;

class TestFixturePlugin extends Plugin
{
    protected $name = 'TestFixture';

    public function getPluginInfo(): array
    {
        return ['name' => $this->name, 'description' => 'Fixture', 'version' => ['version' => '1.0.0']];
    }
}
PHP);
});

test('activating a plugin forgets the cached plugin list', function () {
    writeInstalledPlugins([]);
    Cache::put('wave_installed_plugins', [], 3600);

    Livewire::test(Plugins::class)->call('activate', 'test-fixture');

    expect(readInstalledPlugins())->toBe('["test-fixture"]')
        ->and(Cache::has('wave_installed_plugins'))->toBeFalse();
});

test('deactivating a plugin keeps installed.json a list and forgets the cache', function () {
    writeInstalledPlugins(['test-fixture', 'another-plugin']);
    Cache::put('wave_installed_plugins', ['test-fixture', 'another-plugin'], 3600);

    Livewire::test(Plugins::class)->call('deactivate', 'test-fixture');

    expect(readInstalledPlugins())->toBe('["another-plugin"]')
        ->and(Cache::has('wave_installed_plugins'))->toBeFalse();
});

test('deleting a plugin removes its folder', function () {
    writeInstalledPlugins(['test-fixture']);

    Livewire::test(Plugins::class)->call('deletePlugin', 'test-fixture');

    expect($this->pluginsPath.'/test-fixture')->not->toBeDirectory()
        ->and(readInstalledPlugins())->toBe('[]');
});

test('plugin actions only accept discovered plugin folders', function (string $action) {
    writeInstalledPlugins(['test-fixture']);
    File::ensureDirectoryExists($this->victim);

    Livewire::test(Plugins::class)
        ->call($action, '../plugin-traversal')
        ->assertNotFound();

    expect($this->victim)->toBeDirectory()
        ->and(readInstalledPlugins())->toBe('["test-fixture"]');
})->with(['activate', 'deactivate', 'deletePlugin']);

test('lists plugins generated by plugin:create', function () {
    Http::fake(['cdn.devdojo.com/*' => Http::response('image')]);

    $this->artisan('plugin:create', ['name' => 'SEO Tools'])
        ->expectsQuestion('Provide a short description for your plugin:', 'Search tools')
        ->assertSuccessful();

    Livewire::test(Plugins::class)
        ->assertSet('plugins.seo-tools.name', 'SeoTools')
        ->assertSet('plugins.seo-tools.active', false);
});
